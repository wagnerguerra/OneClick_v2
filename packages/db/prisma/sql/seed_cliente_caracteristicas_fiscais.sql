-- 214 clientes casados por CNPJ. O que NAO entra aqui, de proposito:
--   * 14 CNPJs em que as tres abas discordam do regime entre si;
--   * 2 em que a planilha contraria um cadastro ja preenchido;
--   * 4 CNPJs que nao existem no cadastro (2 sao produtor rural pessoa fisica).
